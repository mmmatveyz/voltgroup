/**
 * tools/test_money.js
 * Автоматический тест для static/js/money.js (Задача 017 / Пункт № 10 AUDIT.md)
 */

import '../static/js/money.js';
const { numberToWordsRu } = globalThis;

const testCases = [
    [1, 'один рубль 00 копеек'],
    [2, 'два рубля 00 копеек'],
    [5, 'пять рублей 00 копеек'],
    [11, 'одиннадцать рублей 00 копеек'],
    [21, 'двадцать один рубль 00 копеек'],
    [1000, 'одна тысяча рублей 00 копеек'],
    [2000, 'две тысячи рублей 00 копеек'],
    [11000, 'одиннадцать тысяч рублей 00 копеек'],
    [1000001, 'один миллион один рубль 00 копеек'],
    [123456.78, 'сто двадцать три тысячи четыреста пятьдесят шесть рублей 78 копеек'],
    // Дополнительные граничные случаи
    [0, 'ноль рублей 00 копеек'],
    [100, 'сто рублей 00 копеек'],
    [1000000, 'один миллион рублей 00 копеек'],
    [2000000, 'два миллиона рублей 00 копеек'],
    [5000000, 'пять миллионов рублей 00 копеек'],
    [0.01, 'ноль рублей 01 копейка'],
    [0.02, 'ноль рублей 02 копейки'],
    [0.05, 'ноль рублей 05 копеек']
];

let failed = 0;
for (const [val, expected] of testCases) {
    const res = numberToWordsRu(val);
    const pass = res === expected;
    console.log(`${pass ? '✓ PASS' : '✗ FAIL'} [${val}] -> "${res}"`);
    if (!pass) {
        console.error(`  Ожидалось: "${expected}"`);
        failed++;
    }
}

if (failed > 0) {
    console.error(`\n❌ Тест завершён с ошибками: ${failed} упало.`);
    process.exit(1);
} else {
    console.log(`\n✅ Все ${testCases.length} тестов успешно пройдены!`);
}
